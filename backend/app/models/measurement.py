"""Physiological-measurement contract."""

from enum import StrEnum
from typing import Self

from pydantic import AwareDatetime, Field, FiniteFloat, model_validator

from app.models.common import ContractModel, Identifier, require_chronological
from app.models.data_quality import DataQuality
from app.models.metrics import MetricType, require_canonical_unit


class MeasurementSource(StrEnum):
    """Where a measurement comes from.

    `simulated` marks synthetic data and must be used for every generated value.
    """

    WEARABLE = "wearable"
    MEDICAL_DEVICE = "medical_device"
    MANUAL_ENTRY = "manual_entry"
    SIMULATED = "simulated"


class PhysiologicalMeasurement(ContractModel):
    """A single value of one metric for one crew member.

    A measurement is either instantaneous (`interval_end` is null) or aggregated over
    the interval from `measured_at` to `interval_end`, as for a night of sleep.
    """

    measurement_id: Identifier = Field(
        description="Unique identifier, generated by the producer of the measurement."
    )
    crew_member_id: Identifier = Field(description="Crew member the measurement refers to.")
    metric: MetricType = Field(description="Measured metric.")
    unit: str = Field(
        description="Unit of `value`. Must be the canonical unit of `metric` (metric_catalog.json)."
    )
    value: FiniteFloat = Field(description="Measured value, expressed in `unit`.")
    measured_at: AwareDatetime = Field(
        description="Instant of the sample, or start of the observation interval (UTC)."
    )
    interval_end: AwareDatetime | None = Field(
        default=None,
        description="End of the observation interval (UTC). Null for instantaneous samples.",
    )
    source: MeasurementSource = Field(description="Origin of the measurement.")
    device_id: Identifier | None = Field(
        default=None, description="Identifier of the producing device, when there is one."
    )
    data_quality: DataQuality | None = Field(
        default=None,
        description="Quality assessment attached by the backend. Null or omitted on ingestion.",
    )

    @model_validator(mode="after")
    def _check_consistency(self) -> Self:
        require_canonical_unit(self.metric, self.unit)
        require_chronological(
            self.measured_at,
            self.interval_end,
            start_field="measured_at",
            end_field="interval_end",
        )
        return self
