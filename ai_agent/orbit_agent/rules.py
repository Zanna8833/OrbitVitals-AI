"""Rule-based content: fixed-wording statements, action catalogue and review flag.

Nothing here is generated by a model. These rules provide

- the complete explanation when no model is available (non-generative fallback);
- the parts of every explanation that must never depend on a model: the limits of the
  data, the recommendation of a human review and the wording of suggested checks.

The suggested checks are operational verification steps (look at the device, find out
why a record is missing, ask a person to review). They are design choices of this
prototype, not clinical guidance, and none of them names a treatment.
"""

from __future__ import annotations

from dataclasses import dataclass

from orbit_agent.evidence.store import ScoredPassage
from orbit_agent.facts import FactSheet
from orbit_agent.models import Fact, HumanReview, Interpretation, Statement

_FLAGGED = {"attention", "alert"}
_MAX_ACTION_FACTS = 6
_MAX_RULE_ISSUE_OBSERVATIONS = 8


@dataclass(frozen=True)
class CandidateAction:
    id: str
    code: str
    text: str
    rationale: str
    fact_ids: tuple[str, ...]
    requires_human_review: bool


def _details(fact: Fact) -> dict:
    return fact.data.get("details_parsed_from_explanation") or {}


def _quality(fact: Fact) -> dict:
    return fact.data.get("data_quality") or {}


def latest_findings(sheet: FactSheet) -> list[Fact]:
    """The most recent finding of each metric (facts are in chronological order)."""
    latest: dict[str, Fact] = {}
    for fact in sheet.of_kind("finding"):
        latest[fact.metric or ""] = fact
    return list(latest.values())


def latest_evaluations(sheet: FactSheet) -> list[Fact]:
    latest: dict[str, Fact] = {}
    for fact in sheet.of_kind("evaluation"):
        if "status" in fact.data:
            latest[fact.domain or ""] = fact
    return list(latest.values())


def _ids(facts: list[Fact]) -> tuple[str, ...]:
    return tuple(fact.id for fact in facts[:_MAX_ACTION_FACTS])


def derive_actions(sheet: FactSheet) -> list[CandidateAction]:
    """Select the catalogue checks whose trigger is present in the facts."""
    findings = sheet.of_kind("finding")
    flagged = [fact for fact in latest_findings(sheet) if fact.data["status"] in _FLAGGED]
    insufficient = [
        fact for fact in latest_findings(sheet) if fact.data["status"] == "insufficient_data"
    ]
    missing = [fact for fact in latest_findings(sheet) if _details(fact).get("missing_nights")]
    issues = sheet.of_kind("measurement_quality_issue")
    artifacts = [fact for fact in issues if "signal_artifact" in _quality(fact).get("flags", [])]
    duplicates = [fact for fact in issues if "duplicate" in _quality(fact).get("flags", [])]
    unconfirmed = [
        fact
        for fact in insufficient
        if "usable_coverage_or_comparison_criteria_missing"
        in _details(fact).get("insufficiency_reasons", [])
    ]
    weak_baselines = [
        fact for fact in sheet.of_kind("baseline") if fact.data["status"] != "established"
    ]
    selected: list[tuple[str, str, str, list[Fact], bool]] = []
    if flagged:
        metrics = ", ".join(sorted({fact.metric or "" for fact in flagged}))
        selected.append(
            (
                "human_review_of_flagged_findings",
                "Ask a qualified person, for example the flight surgeon or the crew medical "
                "officer, to review the flagged findings together with the mission context.",
                f"The backend returned status 'attention' for {metrics}; that status asks "
                "for a review by a person.",
                flagged,
                True,
            )
        )
        selected.append(
            (
                "ask_crew_member_for_context",
                "Ask the crew member about operational factors the records cannot show, such "
                "as schedule changes or workload, before drawing any conclusion.",
                "A flagged pattern in recorded values does not say why the values changed.",
                flagged,
                True,
            )
        )
    if missing:
        selected.append(
            (
                "investigate_missing_records",
                "Find out why records are missing for the listed dates (device not worn, "
                "data not synchronised or a recording gap) before relying on the trend.",
                "The evaluation window has nights without a usable record; missing nights "
                "are not interpreted.",
                missing,
                False,
            )
        )
    if artifacts:
        selected.append(
            (
                "inspect_measurement_chain",
                "Inspect the device and the decoding or transmission chain that produced the "
                "impossible values, and repeat the affected measurements where possible.",
                "The Data Quality Engine marked records as unusable because their values "
                "contradict the definition of the metric.",
                artifacts,
                False,
            )
        )
    if duplicates:
        selected.append(
            (
                "check_duplicate_transmission",
                "Check the acquisition pipeline for repeated transmission of the same record.",
                "The Data Quality Engine found a redundant copy of a stored record.",
                duplicates,
                False,
            )
        )
    if unconfirmed:
        selected.append(
            (
                "confirm_recording_completeness",
                "Confirm which days were recorded completely so that activity can be "
                "evaluated; unconfirmed days remain unknown and are not counted as missed.",
                "No complete usable day was confirmed, so the activity review could not run.",
                unconfirmed,
                False,
            )
        )
    if insufficient:
        selected.append(
            (
                "continue_recording_and_reevaluate",
                "Keep recording and request a new backend evaluation once the window meets "
                "the configured sufficiency rules; until then no status is available.",
                "The latest stored result is 'insufficient_data', which means no "
                "physiological status could be determined.",
                insufficient,
                False,
            )
        )
    if weak_baselines:
        selected.append(
            (
                "regard_baseline_comparison_as_tentative",
                "Regard comparisons with a baseline that is not established as tentative until "
                "more reference data is available.",
                "A personal baseline used here does not have status 'established'.",
                weak_baselines,
                False,
            )
        )
    if not findings and not issues:
        return []
    return [
        CandidateAction(
            id=f"A{index}",
            code=code,
            text=text,
            rationale=rationale,
            fact_ids=_ids(facts),
            requires_human_review=needs_person,
        )
        for index, (code, text, rationale, facts, needs_person) in enumerate(selected, start=1)
    ]


def human_review(sheet: FactSheet) -> HumanReview:
    """Recommend a review by a person whenever a result is flagged or cannot be trusted."""
    reasons: list[str] = []
    fact_ids: list[str] = []
    flagged = [fact for fact in latest_findings(sheet) if fact.data["status"] in _FLAGGED]
    if flagged:
        metrics = ", ".join(sorted({fact.metric or "" for fact in flagged}))
        reasons.append(f"The backend flagged {metrics} with status 'attention'.")
        fact_ids += [fact.id for fact in flagged]
    unusable = [
        fact
        for fact in sheet.of_kind("measurement_quality_issue")
        if _quality(fact).get("status") == "unusable"
    ]
    if unusable:
        reasons.append(
            f"{len(unusable)} stored records are unusable; the cause needs to be checked by a "
            "person."
        )
        fact_ids += [fact.id for fact in unusable]
    undetermined = [
        fact for fact in latest_evaluations(sheet) if fact.data["status"] == "insufficient_data"
    ]
    if undetermined:
        domains = ", ".join(sorted({fact.domain or "" for fact in undetermined}))
        reasons.append(
            f"No status could be determined for {domains}; the system cannot say whether "
            "anything changed."
        )
        fact_ids += [fact.id for fact in undetermined]
    return HumanReview(
        recommended=bool(reasons), reasons=reasons, fact_ids=list(dict.fromkeys(fact_ids))
    )


def rule_headline(sheet: FactSheet) -> str:
    evaluations = latest_evaluations(sheet)
    if not evaluations:
        return "No stored evaluation is available for this crew member in this scope."
    parts = [
        f"{fact.domain}: latest stored status '{fact.data['status']}' "
        f"(window ending {fact.data['window_end']})"
        for fact in evaluations
    ]
    unusable = sum(
        1
        for fact in sheet.of_kind("measurement_quality_issue")
        if _quality(fact).get("status") == "unusable"
    )
    suffix = f" Unusable stored records: {unusable}." if unusable else ""
    return "; ".join(parts) + "." + suffix


def rule_observations(sheet: FactSheet) -> list[Statement]:
    """Restate the facts in their fixed wording, most relevant first."""
    chosen: list[Fact] = []
    evaluations = [fact for fact in sheet.of_kind("evaluation") if "status" in fact.data]
    chosen += [fact for fact in sheet.of_kind("evaluation") if "status" not in fact.data]
    statements: list[Statement] = []
    by_domain: dict[str, list[Fact]] = {}
    for fact in evaluations:
        by_domain.setdefault(fact.domain or "", []).append(fact)
    for domain, facts in by_domain.items():
        if len(facts) > 1:
            listed = "; ".join(
                f"window ending {fact.data['window_end']}: '{fact.data['status']}'"
                for fact in facts
            )
            statements.append(
                Statement(
                    id="",
                    text=f"Stored {domain} evaluations, oldest first: {listed}.",
                    origin="rule",
                    fact_ids=[fact.id for fact in facts],
                )
            )
        else:
            chosen.append(facts[0])
    chosen += latest_findings(sheet)
    chosen += sheet.of_kind("baseline")
    chosen += sheet.of_kind("measurement_series")
    chosen += sheet.of_kind("quality_overview")
    chosen += sheet.of_kind("measurement_quality_issue")[:_MAX_RULE_ISSUE_OBSERVATIONS]
    statements += [
        Statement(id="", text=fact.statement, origin="rule", fact_ids=[fact.id]) for fact in chosen
    ]
    return statements


def rule_interpretations(sheet: FactSheet) -> list[Interpretation]:
    """Readings that follow from the meaning of the statuses alone."""
    baselines = {fact.data["baseline_id"]: fact for fact in sheet.of_kind("baseline")}
    interpretations: list[Interpretation] = []
    for fact in latest_findings(sheet):
        status = fact.data["status"]
        quality_status = _quality(fact).get("status")
        baseline = baselines.get(fact.data.get("baseline_id"))
        # "moderate" is a label of this prototype, not a statistical confidence: it is
        # used only when the backend reports acceptable records and an established
        # baseline. Everything else is "low".
        solid = quality_status == "acceptable" and (
            baseline is not None and baseline.data["status"] == "established"
        )
        cited = [fact.id] + ([baseline.id] if baseline else [])
        if status in _FLAGGED:
            pattern = _details(fact).get("detected_pattern")
            described = f" (configured pattern: {pattern})" if pattern else ""
            interpretations.append(
                Interpretation(
                    id="",
                    text=(
                        f"The configured screen flagged {fact.metric} for review{described}. "
                        "This is a statistical pattern in the recorded values relative to the "
                        "crew member's own baseline. It asks a person to look at the data; it "
                        "does not establish a cause or a health condition."
                    ),
                    origin="rule",
                    fact_ids=cited,
                    kind="screening_signal",
                    confidence="moderate" if solid else "low",
                )
            )
        elif status == "nominal":
            flags = _quality(fact).get("flags") or []
            caveat = (
                f" Records in the same window were flagged ({', '.join(flags)}), which limits "
                "this result further."
                if flags
                else ""
            )
            interpretations.append(
                Interpretation(
                    id="",
                    text=(
                        f"No configured signal was found for {fact.metric} in the usable "
                        "records. This means the screen did not trigger; it does not show "
                        f"that the crew member is well.{caveat}"
                    ),
                    origin="rule",
                    fact_ids=cited,
                    kind="screening_signal",
                    confidence="moderate" if solid else "low",
                )
            )
    issues = sheet.of_kind("measurement_quality_issue")
    if issues:
        interpretations.append(
            Interpretation(
                id="",
                text=(
                    "The flagged records are recording problems: their stored values "
                    "contradict the definition of the metric or repeat another record. They "
                    "describe the data, not the crew member, and support no physiological "
                    "conclusion."
                ),
                origin="rule",
                fact_ids=[fact.id for fact in issues[:_MAX_ACTION_FACTS]],
                kind="data_quality",
                confidence="moderate",
            )
        )
    return interpretations


def rule_uncertainties(sheet: FactSheet, *, has_evidence: bool) -> list[Statement]:
    """Limits that are stated in every explanation, whatever the model writes."""
    statements: list[Statement] = []

    def add(text: str, facts: list[Fact]) -> None:
        statements.append(
            Statement(id="", text=text, origin="rule", fact_ids=[fact.id for fact in facts])
        )

    for fact in latest_findings(sheet):
        if fact.data["status"] == "insufficient_data":
            reasons = _details(fact).get("insufficiency_reasons") or []
            why = f" Reported reasons: {', '.join(reasons)}." if reasons else ""
            add(
                f"No physiological status could be determined for {fact.metric} in the "
                f"latest window: the backend returned 'insufficient_data'.{why} The values "
                "shown for this metric must not be read as normal or abnormal.",
                [fact],
            )
    without_evaluation = [fact for fact in sheet.of_kind("evaluation") if "status" not in fact.data]
    if without_evaluation:
        add(
            "There is no stored evaluation to explain, so nothing can be said about the "
            "crew member's status.",
            without_evaluation,
        )
    missing = [fact for fact in latest_findings(sheet) if _details(fact).get("missing_nights")]
    if missing:
        add(
            "Some nights in the window have no usable record. The reason is unknown, and a "
            "missing night is not evidence of poor or good sleep.",
            missing,
        )
    flagged = [fact for fact in latest_findings(sheet) if fact.data["status"] in _FLAGGED]
    if flagged:
        add(
            "'attention' is produced by screening settings chosen for this demonstration. "
            "They are not clinical thresholds, and the screen is not a statistical "
            "significance test.",
            flagged,
        )
    weak = [fact for fact in sheet.of_kind("baseline") if fact.data["status"] != "established"]
    if weak:
        add(
            "A baseline used for comparison is not established, so the deviation from it is "
            "itself uncertain.",
            weak,
        )
    provenance = sheet.of_kind("provenance")
    if provenance and provenance[0].data["sources"].keys() == {"simulated"}:
        add(
            "All crew data in this explanation is simulated. It shows how the software "
            "behaves, not how a person responds to spaceflight.",
            provenance,
        )
    if has_evidence:
        statements.append(
            Statement(
                id="",
                text=(
                    "The cited summaries of NASA web pages are general context about "
                    "spaceflight. They do not describe this crew member and do not validate "
                    "the screening settings."
                ),
                origin="rule",
            )
        )
    else:
        statements.append(
            Statement(
                id="",
                text=(
                    "No passage in the local evidence corpus matched this question, so no "
                    "scientific source is cited."
                ),
                origin="rule",
            )
        )
    return statements


def rule_evidence_context(passages: list[ScoredPassage]) -> list[Statement]:
    """Show each retrieved entry as stored: a project summary, labelled as such.

    The label names the source page and states that the summary is the project's own
    text, so the information is not presented as a statement made by NASA.
    """
    return [
        Statement(
            id="",
            text=(
                f"OrbitVitals summary of the {item.passage.publisher} web page "
                f'"{item.passage.document_title}" (section "{item.passage.section}"): '
                f"{item.passage.text}"
            ),
            origin="rule",
            evidence_ids=[item.passage.evidence_id],
        )
        for item in passages
    ]
